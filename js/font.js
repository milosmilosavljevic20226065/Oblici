  const KORAK = 6;      // širina ćelije (monospace)

  function glif(ch) {
    if (G[ch]) return G[ch];
    const v = ch.toUpperCase();
    if (G[v]) return G[v];
    return G['?'];
  }

  // Vraća izlomljene linije teksta. velicina = visina velikog slova.
  // opcije.poravnanje: 'levo' | 'centar' | 'desno'; opcije.ugao (radijani)
  function linije(tekst, x, y, velicina, opcije = {}) {
    const k = velicina / 6;
    const razmak = (opcije.razmak ?? 0) + KORAK;
    const sirina = sirinaTeksta(tekst, velicina, opcije);
    let ox = x;
    if (opcije.poravnanje === 'centar') ox = x - sirina / 2;
    else if (opcije.poravnanje === 'desno') ox = x - sirina;
    const ugao = opcije.ugao || 0, cs = Math.cos(ugao), sn = Math.sin(ugao);
    const rez = [];
    let i = 0;
    for (const ch of tekst) {
      for (const l of glif(ch)) {
        rez.push(l.map(([gx, gy]) => {
          const lx = ox + (i * razmak + gx) * k - x;
          const ly = y + gy * k - y;
          return [x + lx * cs - ly * sn, y + lx * sn + ly * cs];
        }));
      }
      i++;
    }
    return rez;
  }

  function sirinaTeksta(tekst, velicina, opcije = {}) {
    const n = [...tekst].length;
    if (!n) return 0;
    const razmak = (opcije.razmak ?? 0) + KORAK;
    return ((n - 1) * razmak + 4) * velicina / 6;
  }

  // SVG putanja (za gravirane natpise na dugmićima i za ploter).
  function svgPutanja(tekst, x, y, velicina, opcije = {}) {
    return linije(tekst, x, y, velicina, opcije)
      .map(l => 'M' + l.map(p => p[0].toFixed(2) + ' ' + p[1].toFixed(2)).join('L'))
      .join('');
  }

  return { linije, sirinaTeksta, svgPutanja };
